_EXPR = re.compile(r"([\d,]+(?:\.\d+)?)\s*만\s*원?\s*[x×X*]\s*([\d.]+)\s*%\s*=\s*(?:약\s*)?([\d,.]+)\s*만\s*(?:(\d)\s*천)?")
_AMT1 = re.compile(r"(\d[\d,]*(?:\.\d+)?)\s*만\s*(?:(\d)\s*천)?\s*원?")
_AMT2 = re.compile(r"(\d{1,3}(?:,\d{3})+)\s*원")
_AMT3 = re.compile(r"(\d[\d,]*)\s*만\s*(\d{1,2},?\d{3})\s*원")   # 123만 7,500원


def expect(income, kind, ps, irp):
    thr = 5500 if kind == "총급여" else 4500
    rate = 16.5 if income <= thr else 13.2
    target = min(min(ps, 600) + irp, 900)
    return rate, target, round(target * rate / 100, 2)


def amounts(text):
    vals = []
    for m in _AMT1.finditer(text):
        try:
            v = float(m.group(1).replace(",", ""))
            if m.group(2): v += int(m.group(2)) / 10
            vals.append(v)
        except ValueError: pass
    for m in _AMT2.finditer(text):
        vals.append(int(m.group(1).replace(",", "")) / 10000)
    for m in _AMT3.finditer(text):
        vals.append(int(m.group(1).replace(",", "")) + int(m.group(2).replace(",", "")) / 10000)
    return vals


def main():
    print(f"계산 경계·조합 {len(Q)}문항 — {BASE}\n")
    ft = open("calc50_out.txt", "w", encoding="utf-8")
    bad, arith_bad, by_group = [], [], {}
    for qid, grp, q, inc, kind, ps, irp in Q:
        rate, target, amount = expect(inc, kind, ps, irp)
        try:
            a = requests.get(BASE, params={"question_id": qid, "question": q}, timeout=180).json().get("answer", "") or ""
        except Exception as e:
            a = f"(요청실패:{str(e)[:40]})"
        body = a.split("[참고 문서]")[0]
        flat = re.sub(r"\s+", "", body)
        wrong_rate = "13.2" if rate == 16.5 else "16.5"
        ok_rate = str(rate) in flat
        # 반대 세율이 곱셈식에 쓰였는지 (구간 설명으로 언급된 건 허용)
        wrong_applied = bool(re.search(rf"[x×X*]{wrong_rate}%", flat))   # 곱셈식에 반대 세율
        ok_target = (f"{target}만" in flat) or (f"{target:,}만" in flat)
        ok_amount = any(abs(v - amount) <= 0.11 for v in amounts(body))
        # 답변 속 곱셈식 산술 검증
        arith = []
        for m in _EXPR.finditer(body):
            try:
                A = float(m.group(1).replace(",", "")); R = float(m.group(2)); C = float(m.group(3).replace(",", ""))
                if m.group(4): C += int(m.group(4)) / 10          # '118만8천원' → 118.8
                if abs(A * R / 100 - C) > 0.06: arith.append(m.group(0))
            except ValueError: pass
        flags = []
        if not ok_rate: flags.append("세율")
        if wrong_applied: flags.append("반대세율적용")
        if not ok_target: flags.append("대상")
        if not ok_amount: flags.append("공제액")
        if arith: flags.append("산술식오류")
        tag = "OK" if not flags else "★" + ",".join(flags)
        by_group.setdefault(grp, [0, 0]); by_group[grp][1] += 1
        if not flags: by_group[grp][0] += 1
        else: bad.append((qid, grp, flags))
        if arith: arith_bad.append((qid, arith))
        print(f"  [{qid:3}][{grp}] 기대 {rate}% 대상{target}만 공제{amount:g}만 → {tag}")
        ft.write(f"\n{'='*70}\n[{qid}][{grp}] {q}\n기대: 세율 {rate}% / 대상 {target}만 / 공제액 {amount:g}만  판정: {tag}\n--- 답변 ---\n{a}\n")
        time.sleep(0.3)
    ft.close()
    print("\n" + "=" * 60)
    for g, (ok, n) in by_group.items():
        print(f"  {g:8} {ok}/{n}")
    if arith_bad:
        print(f"★ 산술식 오류 {len(arith_bad)}건: {arith_bad}")
    if bad:
        print(f"★ 확인 필요 {len(bad)}/{len(Q)}: " + ", ".join(f"{q}({','.join(f)})" for q, _, f in bad))
        print("→ calc50_out.txt 원문으로 표기차/실오류 판단")
    else:
        print(f"{len(Q)}문항 모두 세율·대상·공제액·산술 일치 → 계산 경로 잠금 가능")
    print("=" * 60)


if __name__ == "__main__":
    main()
