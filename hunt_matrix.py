# ── Part B: 문서에서 자동 생성 ─────────────────────────────────
#   판정 로직은 main.py에서 그대로 꺼내 쓴다(규칙을 두 군데 두지 않는다).
def build_from_docs():
    src = open("main.py", encoding="utf-8").read()
    ns = {"re": re}
    exec(src[src.index("# 등급 표기는 운용사마다 다르다"):src.index("def _src_text(")], ns)
    rg, rv, rn = ns["_read_grade"], ns["_read_vol"], ns["_read_name"]
    HIST = re.compile(r"위험등급\s*변경\s*\[\s*([1-6])등급[^\]]*?→\s*([1-6])등급")

    chunks = json.load(open("chunks.json", encoding="utf-8"))
    by = {}
    for c in chunks:
        by.setdefault(c["source"], []).append(c["text"])

    docs = []
    for s, ts in sorted(by.items()):
        t = " ".join(ts)
        if "집합투자기구" not in t:
            continue
        nm = rn(t)
        g, lab = rg(t)
        if not nm or g is None:
            continue
        v, k = rv(t)
        h = HIST.search(t)
        trap = bool(h and int(h.group(1)) != g)
        docs.append({"src": s, "name": nm, "grade": g, "label": lab,
                     "vol": v, "vkind": k, "trap": trap,
                     "hist": (int(h.group(1)) if h else None)})

    out = []
    def mk(cat, q, look, expect=None):
        out.append((f"B{len(out)+1:02d}", cat, q, look, expect))

    # 1) 이력 함정 문서 — 과거 등급을 현재로 답하면 오류
    for d in [x for x in docs if x["trap"]][:8]:
        mk("함정-이력", f"{d['name']}의 현재 위험등급이 몇 등급인가요?",
           f"정답 {d['grade']}등급({d['label']}). 이력의 {d['hist']}등급을 답하면 오류",
           {"grade": d["grade"], "wrong": d["hist"]})

    # 2) 등급이 서로 다른 두 상품 — '모두 같다'로 묶으면 오류
    diff = [(a, b) for i, a in enumerate(docs) for b in docs[i + 1:]
            if abs(a["grade"] - b["grade"]) >= 2][:4]
    for a, b in diff:
        mk("비교-등급차", f"{a['name']}와(과) {b['name']} 중 안정적인 걸 원해요. 뭐가 다른가요?",
           f"{a['name']}={a['grade']}등급 / {b['name']}={b['grade']}등급. "
           f"'둘 다 같다'거나 등급을 뒤바꾸면 오류",
           {"grades": [a["grade"], b["grade"]]})

    # 3) 변동성 척도가 다른 두 상품 — 나란히 비교하면 오류
    kinds = {}
    for d in docs:
        if d["vol"] is not None:
            kinds.setdefault(d["vkind"], []).append(d)
    ks = [k for k, v in kinds.items() if v]
    for i in range(len(ks)):
        for j in range(i + 1, len(ks)):
            a, b = kinds[ks[i]][0], kinds[ks[j]][0]
            mk("비교-척도혼용",
               f"{a['name']}와(과) {b['name']}의 변동성을 비교해서 어느 쪽이 더 안정적인지 알려주세요.",
               f"척도가 다름({ks[i]} vs {ks[j]}). 두 수치를 나란히 놓고 우열을 말하면 오류")

    # 4) 등급이 같은 두 상품 — 변동성으로 실질 차이를 제시하는지
    same_k = [d for d in docs if d["vol"] is not None and d["vkind"] == "3년 97.5% VaR"]
    for i in range(0, min(len(same_k) - 1, 4), 2):
        a, b = same_k[i], same_k[i + 1]
        if a["grade"] == b["grade"]:
            mk("비교-등급동일",
               f"{a['name']}와(과) {b['name']}은 위험등급이 같은데 뭐가 다른가요? 안정적인 걸 원해요.",
               f"등급 동일({a['grade']}등급). 변동성 {a['vol']}% vs {b['vol']}% 로 구분해야")
    return out, docs


# ── 실행 ──────────────────────────────────────────────────────
def ask(qid, q):
    try:
        d = requests.get(BASE, params={"question_id": qid, "question": q},
                         timeout=300).json()
        return d.get("answer", ""), d.get("think_trace", "")
    except Exception as e:
        return f"[호출 실패: {e}]", ""


def main():
    auto, docs = build_from_docs()
    total = len(S) + len(auto)
    print(f"허점 사냥 매트릭스: 정적 {len(S)}건 + 문서기반 {len(auto)}건 = {total}건")
    print(f"(투자설명서 {len(docs)}건 분석, 이력 함정 {sum(1 for d in docs if d['trap'])}건)\n")
    t0 = time.time()
    flagged, human = [], []

    items = [(i, c, q, look, None) for i, c, q, look in S] + list(auto)
    for n, (qid, cat, q, look, expect) in enumerate(items, 1):
        el = time.time() - t0
        eta = (el / (n - 1) * (total - n + 1)) if n > 1 else 0
        print(f"[{n:3d}/{total}] {qid} ({cat})  경과 {el/60:.1f}분 / 남은 {eta/60:.1f}분", flush=True)
        print("=" * 78, flush=True)
        print(f"Q. {q}", flush=True)
        print(f"   볼 포인트: {look}", flush=True)
        ans, trace = ask(qid, q)
        bad = auto_check(q, ans, trace)
        # 문서기반 항목은 정답 등급을 알고 있으므로 직접 대조한다
        if expect and "grade" in expect:
            said = {int(x) for x in re.findall(r"([1-6])\s*등급", ans)}
            if expect["wrong"] in said and expect["grade"] not in said:
                bad.append(f"이력의 과거 등급({expect['wrong']}등급)을 현재로 답함")
            elif said and expect["grade"] not in said:
                bad.append(f"등급 불일치: 답변 {sorted(said)} / 정답 {expect['grade']}등급")
        if expect and "grades" in expect:
            said = {int(x) for x in re.findall(r"([1-6])\s*등급", ans)}
            miss = [g for g in expect["grades"] if g not in said]
            if said and miss:
                bad.append(f"등급 누락/오기: 답변 {sorted(said)} / 정답 {expect['grades']}")
        if bad:
            flagged.append((qid, cat, q, bad))
            print("  ### 자동 검사 걸림:", flush=True)
            for b in bad:
                print(f"      - {b}", flush=True)
        else:
            human.append((qid, cat))
        print(f"[trace] {trace}", flush=True)
        print(f"[answer]\n{ans}\n", flush=True)
        time.sleep(PACE)

    print("=" * 78)
    print(f"===== 사냥 결과: {total}건 중 자동 검사 걸림 {len(flagged)}건 =====")
    for qid, cat, q, bad in flagged:
        print(f"  [{qid}] ({cat}) {q[:44]}…")
        for b in bad:
            print(f"        └ {b}")
    print(f"\n나머지 {len(human)}건은 위 답변을 사람이 '볼 포인트' 기준으로 읽어야 합니다.")
    print(f"총 소요 {(time.time()-t0)/60:.1f}분")


if __name__ == "__main__":
    main()
