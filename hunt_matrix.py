#   사용법: 서버 켠 상태에서
#     nohup python3 -u hunt_matrix.py > hunt_matrix.txt 2>&1 & P=$!; sleep 1; tail -f --pid=$P hunt_matrix.txt
#
#   설계 원칙
#   1) 회귀 50건이 '이미 고친 것'이라면, 여기는 '아직 모르는 것'을 찾는다.
#      → 한 질문에 함정을 2~3개 겹쳐 놓는다. 실제 오류는 단독이 아니라 조합에서 났다.
#   2) 100건을 사람이 다 읽을 수 없으므로, 기계로 판정 가능한 것은 기계가 판정한다.
#      · 산수 검산 : 답변 속 'A만원 × B% = C만원' 을 실제로 곱해 대조
#      · 등급 검산 : 'N등급(라벨)' 이 표준 6단계와 어긋나면 오류
#      · 공통 금지 : 내부 순번, HTML, 구기준 한도, 가짜 기한, 개인정보 되풀이
#   3) 기계가 못 잡는 것은 '볼 포인트'를 함께 출력해 사람이 읽는다.
