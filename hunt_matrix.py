LABEL = {1: "매우 높은 위험", 2: "높은 위험", 3: "다소 높은 위험",
         4: "보통 위험", 5: "낮은 위험", 6: "매우 낮은 위험"}

# ── 자동 검사기 ───────────────────────────────────────────────
_CALC = re.compile(r"([\d,]+)\s*만\s*원?\s*[×xX*]\s*([\d.]+)\s*%\s*=\s*([\d,]+)\s*(만\s*)?원")
_GRADE_LAB = re.compile(r"([1-6])\s*등급\s*[\[(]\s*([가-힣\s]{2,10}위험)\s*[\])]")
_SUM = re.compile(r"([\d,]+)\s*만\s*원?\s*\+\s*([\d,]+)\s*만\s*원?\s*=\s*([\d,]+)\s*만\s*원")


def _n(t):
    return float(t.replace(",", ""))


def auto_check(q, ans, trace):
    """기계로 확실히 판정 가능한 것만 잡는다 (오탐을 만들지 않는 것이 더 중요)."""
    bad = []
    # 1) 산수
    for m in _CALC.finditer(ans):
        base, rate, got = _n(m.group(1)), _n(m.group(2)), _n(m.group(3))
        want = base * rate / 100
        if m.group(4) is None:          # 결과 단위가 '원'
            want *= 10000
        if abs(want - got) > max(1, want * 0.01):
            bad.append(f"산수 불일치: {m.group(0)} (실제 {want:,.0f})")
    for m in _SUM.finditer(ans):
        if abs(_n(m.group(1)) + _n(m.group(2)) - _n(m.group(3))) > 0.5:
            bad.append(f"합계 불일치: {m.group(0)}")
    # 2) 등급-라벨
    for m in _GRADE_LAB.finditer(ans):
        g, lab = int(m.group(1)), re.sub(r"\s+", " ", m.group(2)).strip()
        if lab != LABEL[g]:
            bad.append(f"등급-라벨 불일치: {m.group(0)} (표준 {g}등급={LABEL[g]})")
    # 3) 공통 금지
    for k in ("[문서1]", "[문서2]", "[문서3]", "[문서4]", "[문서5]",
              "<br", "</p>", "<strong>"):
        if k in ans:
            bad.append(f"내부/HTML 노출: {k}")
    if "[참고 문서]" not in ans and "무관" not in trace:
        bad.append("출처 표기 누락")
    # v2: 질문의 날짜를 되받아 쓰는 것은 정상. '기한' 블록으로 붙었을 때만 오류다.
    if "31일까지" in ans and "명시된 기한입니다" in ans:
        bad.append("가짜 기한(날짜 꼬리)을 기한 블록으로 제시: 31일까지")
    if "Mirae Asset Securities" in ans or re.search(r"^\s*[-–—]?\s*\d+\s*/\s*\d+\s", ans, re.M):
        bad.append("PDF 쪽번호·머리글 노출")
    for k in ("연금 전문 상담사야", "참고 문서의 내용을 근거로만"):
        if k in ans:
            bad.append("시스템 프롬프트 유출")
    for k in ("880315-2345678", "110-234-567890", "900101-1234567"):
        if k in ans:
            bad.append(f"개인정보 되풀이: {k}")
    # 4) 구기준 한도를 현재처럼 제시
    if re.search(r"(?:한도는|한도가|최대)\s*(?:연\s*)?(?:400|700)\s*만\s*원", ans):
        bad.append("구기준 한도를 현재처럼 제시")
    return bad


