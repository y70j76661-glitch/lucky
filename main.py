# v9.14: '자료에 없다'고 밝힌 뒤 일반 상식을 덧붙이는 문제 (오류사냥 [7] 재발)
#   프롬프트로 한 번 막았다가 재발했으므로 코드로 잘라낸다.
# v9.24: 실측 — "명확히 지정할 수 없습니다"가 목록에 없어 필터가 통째로 꺼졌다.
#   '~할 수 없다 / ~어렵다' 계열을 폭넓게 잡는다.
_NOINFO = re.compile(r"(확인할 수 없|확인되지 않|확인이 어렵|포함되어 있지 않|자료에 없|"
                     r"자료에는 없|찾을 수 없|나와 있지 않|나와있지 않|명시되어 있지 않|"
                     r"제시되어 있지 않|제시되지 않|매기지 않|"
                     r"(?:지정|특정|선정|단정|answer|골라|선택)할 수 없|"
                     r"알려드릴 수 없|확답을 드릴 수 없|말씀드리기 어렵|"
                     r"비교하기 어렵|제공하기 어렵|판단하기 어렵|파악할 수 없|"
                     r"드릴 수 없|알 수 없)")
_OUTSIDE = re.compile(r"^\s*(?:일반적으로|통상|보통|참고로|다만,?\s*일반적|알려진 바|"
                      r"일반적인 경우|시중에서는)")
_HASNUM = re.compile(r"\d+\s*(?:%|퍼센트|만\s*원|원)")


# v9.15: '그러나 일반적으로 …' 처럼 문장 중간에 붙는 일반론도 잡기 위해 문장 단위로 검사
_GENERAL = re.compile(r"(?:^|[.!?]\s*|그러나\s*|하지만\s*|다만,?\s*|또한,?\s*)"
                      r"(?:일반적으로|일반적인 경우|통상적으로|통상|보통|시중에서는|"
                      r"알려진 바에 따르면|알려져 있)")


# v9.16: 문장에 들어 있는 수치가 참고 문서에 실제로 있으면 그 문장은 '근거 있음'이다.
#   (v9.15 필터가 연금소득세 3.3~5.5% 문장까지 지워버린 사고를 막는다)
_PCT = re.compile(r"(\d+(?:\.\d+)?)\s*%")
_WON = re.compile(r"([\d,]+)\s*만\s*원")


def _grounded(sent, context):
    """문장 속 수치가 참고 문서에서 확인되면 True"""
    if not context:
        return False
    for v in _PCT.findall(sent):
        if re.search(r"(?<![\d.])" + re.escape(v) + r"\s*%", context):
            return True
    for v in _WON.findall(sent):
        v2 = v.replace(",", "")
        if re.search(r"(?<![\d,])" + re.escape(v) + r"\s*만\s*원", context) or \
                re.search(r"(?<![\d,])" + re.escape(v2) + r"\s*만\s*원", context):
            return True
    return False


def strip_outside_knowledge(ans, context=""):
    """'자료에 없다'고 답한 뒤 붙은 문서 밖 설명을 삭제 (문장 단위).
    단, 문서에서 확인되는 수치가 든 문장은 근거가 있으므로 남긴다."""
    # v9.15: '자료에 없다'는 고백이 답변 어디에든 있으면 그 답변 전체에 필터를 건다.
    #   (뒷문단에서 고백하고 앞문단에서 일반론을 펴는 형태가 실제로 나왔다)
    if not _NOINFO.search(ans):
        return ans, ""
    out_lines, removed = [], 0
    for line in ans.split("\n"):
        if not line.strip():
            out_lines.append(line)
            continue
        # 문장 단위로 문서 밖 일반론을 걸러낸다
        sents = re.split(r"(?<![0-9]\.)(?<=[.!?])\s+", line)
        keep = []
        just_dropped = False
        for sent in sents:
            drop = bool(_GENERAL.search(sent)) and (
                bool(_HASNUM.search(sent)) or "경향" in sent or "가능성" in sent
                or "일반적으로" in sent)
            # v9.24: 말머리 없이 '~하는 경향이 있습니다'로 단정하는 일반론도 제거
            if not drop and ("경향이 있" in sent or "경향이 큽" in sent
                             or "일반적으로" in sent):
                drop = True
            # v9.16: 삭제된 문장을 이어받는 부연 문장('이는 … 4.5%입니다')도 함께 정리
            if not drop and just_dropped and _HASNUM.search(sent) and \
                    re.match(r"\s*(?:이는|이것은|이 경우|또한|그리고|따라서|즉|여기서)", sent):
                drop = True
            # 문서 출처가 명시됐거나, 수치가 문서에서 확인되면 근거가 있으므로 남긴다
            if drop and "출처" not in sent and not _grounded(sent, context):
                removed += 1
                just_dropped = True
                continue
            just_dropped = False
            keep.append(sent)
        if keep:
            out_lines.append(" ".join(keep))
        elif not sents:
            out_lines.append(line)
    if not removed:
        return ans, ""
    ans = "\n".join(ln for ln in out_lines
                    if not re.fullmatch(r"\s*(?:\d+[.)]|[-*•])\s*", ln))
    ans = re.sub(r"\n{3,}", "\n\n", ans).strip()
    # 목록 번호가 비면 다시 매긴다
    cnt = [0]

    def _renum(m):
        cnt[0] += 1
        return f"{m.group(1)}{cnt[0]}."
    if re.search(r"^\s*\d+\.", ans, flags=re.M):
        ans = re.sub(r"^(\s*)\d+\.", _renum, ans, flags=re.M)
    return ans, f" (문서 밖 설명 {removed}건 삭제)"


# v9.14: 16.5%와 13.2%를 한 식에서 더하던 오류 (오류사냥 [5])
_MIXED = re.compile(
    r"[^\n]*?16\.5\s*%[^\n]{0,40}\+[^\n]{0,40}13\.2\s*%[^\n]*"
    r"|[^\n]*?13\.2\s*%[^\n]{0,40}\+[^\n]{0,40}16\.5\s*%[^\n]*")


def fix_mixed_rate(ans, paid=None):
    """한 사람에게 두 공제율을 동시 적용한 계산식을 구간별 안내로 교체.
    그 식이 만들어낸 '틀린 합계 금액'이 본문에 남아 있으면 그 문장도 제거한다."""
    base = min(paid, 900) if paid else 900
    fix = (f"세액공제율은 소득에 따라 둘 중 하나만 적용됩니다. "
           f"총급여 5,500만원 이하면 {int(base):,}만원 \u00d7 16.5% = 약 {base * 0.165:,.1f}만원, "
           f"5,500만원을 초과하면 {int(base):,}만원 \u00d7 13.2% = 약 {base * 0.132:,.1f}만원입니다.")
    wrong_totals = []

    def _sub(m):
        # 잘못된 식의 마지막 '= N만원' 값 = 틀린 합계
        vals = re.findall(r"=\s*\**\s*([\d,]+\.?\d*)\s*만", m.group(0))
        if vals:
            wrong_totals.append(vals[-1].replace(",", ""))
        return fix

    ans2, n = _MIXED.subn(_sub, ans)
    if not n:
        return ans, ""
    for w in set(wrong_totals):
        good = {f"{base * 0.165:,.1f}", f"{base * 0.132:,.1f}"}
        if w in {g.replace(",", "") for g in good}:
            continue                       # 우연히 맞는 값이면 건드리지 않음
        pat = re.compile(r"(?<![\d.])" + re.escape(w) + r"\s*만\s*원?")
        keep = [ln for ln in ans2.split("\n") if not pat.search(ln)]
        ans2 = "\n".join(keep)
    ans2 = re.sub(r"\n{3,}", "\n\n", ans2).strip()
    return ans2, f" (공제율 혼용 교정 {n}건)"


def post_with_retry(url, payload, timeout=45, tries=3):
    """API 호출 공통 함수: 실패하면 쉬었다 재시도.
    v7.5: 속도 제한(429)은 더 길게 기다리며 재시도 (연속 질문 심사 대비)
    v9.27: 5회x60초는 최악의 경우 수 분이 걸려 무응답 위험이 커서 3회x45초로 줄였다."""
    last_err = None
    for i in range(tries):
        wait = 1.5 * (i + 1)
        try:
            r = requests.post(url, headers=HEADERS, json=payload, timeout=timeout)
            if r.status_code == 200:
                return r
            last_err = Exception(f"HTTP {r.status_code}")
            if r.status_code == 429:  # 속도 제한: 충분히 길게 대기
                wait = 6.0 * (i + 1)  # 6초 → 12초 → 18초 → 24초
        except Exception as e:
            last_err = e
        time.sleep(wait)
    raise last_err


