def _read_name(text):
    """상품(펀드) 이름을 읽는다. 표기 형식이 운용사마다 달라 여러 단서를 쓴다."""
    cands = []
    for mark in _NAME_MARKS:
        m = mark.search(text)
        if not m:
            continue
        seg = text[max(0, m.start() - 80):m.start()]
        seg = _NAME_CUT.split(seg)[-1]
        seg = _NAME_TAIL.sub("", seg).strip(" .:·-")
        seg = re.sub(r"\s{2,}", " ", seg)
        if 4 <= len(seg) <= 60 and ("투자신탁" in seg or "펀드" in seg or "증권" in seg):
            cands.append(seg)
    m = _FUND_NAME.search(text)
    if m:
        nm = re.sub(r"\s{2,}", " ", m.group(1).strip(" .:·-"))
        if 4 <= len(nm) <= 60:
            cands.append(nm)
    m2 = re.search(r"([가-힣A-Za-z0-9]+증권자?투자신탁[^\s]{0,20})", text)
    if m2:
        cands.append(m2.group(1))
    return cands[0] if cands else None


def _read_grade(text):
    """문서 전체에서 '현재 위험등급'을 읽는다. → (등급, 라벨) 또는 (None, None)"""
    for pat in _GRADE_PATS:
        for m in pat.finditer(text):
            win = text[max(0, m.start() - 70):m.start()]
            if any(w in win for w in _GRADE_TRAP):
                continue
            if "→" in text[m.start():m.end() + 20]:
                continue
            g = int(m.group(1))
            lab = (m.group(2) or "").strip()
            lab = re.sub(r"\s+", " ", lab)
            if not lab and "매우 낮은 위험" in text and "매우 높은 위험" in text:
                lab = _LABEL_BY_GRADE[g]      # 문서가 6단계 척도를 싣고 있을 때만
            return g, (lab or None)
    return None, None


def _read_vol(text):
    """변동성을 읽되 '어느 척도인지'를 함께 반환한다. → (값, 척도) 또는 (None, None)"""
    for pat, kind in _VOL_PATS:
        m = pat.search(text)
        if m:
            try:
                return float(m.group(1)), kind
            except ValueError:
                pass
    return None, None


