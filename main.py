import math
from collections import Counter

def _tok(text):
    """한국어 대응 토큰화: 공백 단어 + 2글자 조각(바이그램)"""
    words = text.lower().split()
    grams = []
    for w in words:
        grams.append(w)
        grams += [w[i:i + 2] for i in range(len(w) - 1)]
    return grams

