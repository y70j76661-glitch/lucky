def _risk_lines(prof):
    items = sorted(prof.items(), key=lambda kv: (-kv[1]["grade"], kv[1]["short"]))
    grades = " / ".join(
        f"{r['short']} {r['grade']}등급" + (f"[{r['label']}]" if r["label"] else "")
        for _n, r in items)
    kinds = {r["vkind"] for _n, r in items if r["vol"] is not None}
    if len(kinds) == 1:      # v9.45: 척도가 섞이면 비교하지 않는다
        vols = [(r["short"], f"{r['vol']:.2f}") for _n, r in items if r["vol"] is not None]
        vkind = kinds.pop()
    else:
        vols, vkind = [], None
    return grades, sorted(vols, key=lambda x: float(x[1])), vkind


