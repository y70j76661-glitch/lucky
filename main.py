# ── v9.48: 문서에 없는 것을 '추측'으로 채우지 않는다 ──────────────────────
#   실측: 비교표 칸에 "별도 명시되지 않으나 비교적 짧을 것으로 예상됨",
#         "명시되지 않았으나 일반적으로 동일하게 적용될 가능성 있음" 이 들어갔다.
#   '자료에 없다'고 스스로 말하면서 그 자리를 추측으로 메우는 것은 근거 기반 위반이다.
#   → 두 신호가 한 칸(또는 한 문장)에 같이 있으면 '자료 없음'으로 되돌린다.
_NOSTATE = re.compile(r"(?:명시|기재|제시|언급|확인)\s*되?\s*(?:지|가|이)?\s*"
                      r"(?:않|아니|못하)[가-힣]*\s*(?:으나|지만|나|고)")
_GUESS = ("예상", "추정", "가능성", "보입니다", "보임", "것으로 판단", "일 것", "듯",
          "일반적으로", "통상")
_NOINFO_CELL = "자료 없음"


def strip_speculation(ans):
    """'자료에 없다'고 말하면서 추측으로 메운 칸·문장을 정리한다. → (답변, 건수)"""
    n = 0
    out = []
    for line in ans.splitlines():
        if line.count("|") >= 2:                      # 표: 해당 칸만 '자료 없음'으로
            cells = line.split("|")
            for i, c in enumerate(cells):
                if _NOSTATE.search(c) and any(g in c for g in _GUESS):
                    cells[i] = f" {_NOINFO_CELL} "
                    n += 1
            out.append("|".join(cells))
            continue
        keep = []
        for sent in re.split(r"(?<![0-9]\.)(?<=[.!?])\s+", line):
            if _NOSTATE.search(sent) and any(g in sent for g in _GUESS):
                n += 1
                continue
            keep.append(sent)
        out.append(" ".join(k for k in keep if k.strip()))
    if not n:
        return ans, 0
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)), n


# ── v9.42: 일부만 확인된 항목을 '모든 상품이 ~'로 일반화하면 주의를 붙인다 ──────
#   실측: 장기의 보수가 '자료 없음'인데 "모든 유형에서 C-P가 가장 낮다"고 단정했다.
_ALL_WORDS = ("모든", "전부", "모두", "공통적으로", "일괄")


def warn_partial_generalization(ans):
    lines = ans.splitlines()
    idx = [i for i, ln in enumerate(lines) if ln.count("|") >= 2]
    if len(idx) < 3:
        return ans, 0
    partial = []
    for i in idx[1:]:
        c = _cells(lines[i])
        if len(c) >= 3 and any("자료 없음" in x for x in c[1:]) \
                and not all("자료 없음" in x for x in c[1:]):
            partial.append(c[0])
    if not partial:
        return ans, 0
    # v9.43: 표 라벨('수수료(보수)')과 본문 표현('수수료 범위')이 달라 놓치던 문제
    body = [ln for ln in lines if ln.count("|") < 2]
    hit = []
    for lab in partial:
        keys = [k for k in re.split(r"[()·\s/]+", lab) if len(k) >= 2]
        if any(any(k in ln for k in keys) and any(w in ln for w in _ALL_WORDS)
               for ln in body):
            hit.append(lab)
    if not hit:
        return ans, 0
    note = ("※ " + "·".join(f"'{h}'" for h in hit)
            + " 항목은 일부 상품의 값이 자료에서 확인되지 않아, 세 상품 전체에 대한 "
              "일반화가 아니라 확인된 상품에 한한 설명입니다.")
    if note in ans:
        return ans, 0
    return ans.rstrip() + "\n\n" + note, len(hit)



