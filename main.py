def filter_by_relevance(docs, scores, min_keep=REL_MIN_KEEP):
    """v9.38: 관련도가 낮은 문서를 근거에서 제외한다.
    반환: (남긴 문서, 남긴 점수, 제외한 점수 목록)"""
    if len(docs) <= min_keep:
        return docs, scores, []
    top = max(scores)
    thr = max(top * REL_RATIO, REL_FLOOR)
    keep = [i for i, sc in enumerate(scores) if sc >= thr]
    if len(keep) < min_keep:                      # 너무 많이 잘리면 상위부터 다시 채운다
        order = sorted(range(len(scores)), key=lambda i: -scores[i])
        keep = sorted(order[:min_keep])
    drop = [i for i in range(len(docs)) if i not in keep]
    return ([docs[i] for i in keep], [scores[i] for i in keep],
            [round(scores[i], 3) for i in drop])


def search(question, top_k=5):
    """하이브리드 검색: 임베딩(의미) + BM25(키워드) 순위 결합(RRF).
    반환: (문서 목록, 각 문서의 임베딩 유사도, 임계값 판정용 최고 임베딩 유사도)"""
    res = post_with_retry(EMB_URL, {"text": question}, timeout=30)
    q = np.array(res.json()["result"]["embedding"])
    q = q / np.linalg.norm(q)
    emb_scores = matrix @ q
    top_score = float(emb_scores.max())  # 무관 판정은 기존처럼 임베딩 기준 유지

    if HYBRID:
        kw_scores = bm25_scores(question)
        # 점수 정규화 결합: 임베딩(의미) 0.6 + 키워드(정확 용어) 0.4
        def _norm(x):
            span = x.max() - x.min()
            return (x - x.min()) / span if span > 0 else np.zeros_like(x)
        fused = 0.6 * _norm(emb_scores) + 0.4 * _norm(kw_scores)
        order = np.argsort(-fused)[:top_k]
    else:
        order = np.argsort(-emb_scores)[:top_k]

    docs = [chunks[idx_list[i]] for i in order]
    doc_scores = [float(emb_scores[i]) for i in order]
    return docs, doc_scores, top_score


