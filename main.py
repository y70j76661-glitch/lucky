def verify_answer(context, draft, allow_fix=True):
    """초안을 문서와 대조. (최종 답변, 수정 여부, 사유) 반환. 실패 시 초안 유지.
    allow_fix=False면 판정만 하고 재작성은 건너뛴다 (v9.27: 시간 예산)."""
    try:
        user_msg = f"참고 문서:\n{context}\n\n답변:\n{draft}"
        text = chat(VERIFY_CHECK_SYSTEM, user_msg, max_tokens=150, temperature=0.1)
        m = re.search(r"\{.*\}", text or "", re.S)
        verdict = json.loads(m.group()) if m else {}
        if not verdict.get("불일치"):
            return draft, False, ""      # 판정: 이상 없음 → 초안 그대로
        reason = str(verdict.get("사유", "문서와 불일치"))[:60]
        if not allow_fix:                     # v9.27: 시간이 없으면 재작성 생략
            return draft, False, reason + "(시간 예산으로 재작성 생략)"
        fixed = chat(VERIFY_FIX_SYSTEM,
                     user_msg + f"\n\n발견된 문제: {reason}",
                     max_tokens=600, temperature=0.1)
        if fixed and len(fixed.strip()) >= 30:
            return fixed.strip(), True, reason
    except Exception:
        pass
    return draft, False, ""              # 검증 실패 → 초안 유지


