_DOUBLE_TAX_FIX = ("중도 해지 시에는 세액공제를 받은 납입금과 운용수익에 대해 "
                   "기타소득세 16.5%가 부과됩니다.")


def fix_double_tax(ans):
    """세액공제 반환 + 기타소득세를 이중으로 물리는 문장을 제거한다.
    제거 후 기타소득세 설명이 남아 있지 않으면 문서 기준 문장을 대신 넣는다."""
    if "기타소득세" not in ans:
        return ans, ""
    out, cnt = [], 0
    for line in ans.split("\n"):
        if _DOUBLE_TAX.search(line) and "받지 않은" not in line:
            # 목록 항목이면 항목 전체를 덜어낸다 (앞뒤 문장이 함께 어긋나 있으므로)
            if re.match(r"\s*(?:\d+[.)]|[-*•])", line):
                cnt += 1
                continue
            sents = re.split(r"(?<![0-9]\.)(?<=[.!?])\s+", line)
            keep = [x for x in sents
                    if not (_DOUBLE_TAX.search(x) and "받지 않은" not in x)]
            cnt += len(sents) - len(keep)
            if keep:
                out.append(" ".join(keep))
            continue
        out.append(line)
    if not cnt:
        return ans, ""
    ans = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()
    # 남은 본문에 기타소득세 설명이 사라졌으면 문서 기준 문장으로 채운다
    if not (re.search(r"기타소득세[^\n]{0,20}16\.5", ans)
            or re.search(r"16\.5[^\n]{0,20}기타소득세", ans)):
        ans = _DOUBLE_TAX_FIX + "\n\n" + ans
    # 목록 번호가 어긋나면 다시 매긴다
    n = [0]

    def _renum(m):
        n[0] += 1
        return f"{n[0]}."
    if re.search(r"^\s*\d+\.", ans, flags=re.M):
        ans = re.sub(r"^(\s*)\d+\.", lambda m: m.group(1) + _renum(m), ans, flags=re.M)
    return ans, f" (이중과세 표현 교정 {cnt}건)"


