        ans = re.sub(r"\(출처:\s*([^)]+)\)\s*\(\s*\1\s*\)", r"(출처: \1)", ans)

        # [6.8단계] v9.18: 질문과 직접 관련된 기한이 답변에서 빠졌으면 문서 문장으로 보강
        miss = [(n, t) for n, t in forced_pairs if n not in ans.replace(" ", "")]
