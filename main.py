def extract_risk_profile(sources):
    """v9.44: 출처 목록을 받아, 각 문서의 '전체 청크'에서
    (상품명, 현재 위험등급, 라벨, 3년 변동성)을 읽는다.
    등급은 '투자위험등급 N등급[라벨]' 표기에서만 읽고 변경 이력은 배제한다."""
    prof = {}
    for src in sources:
        text = _src_text(src)
        if not text:
            continue
        name = _read_name(text)
        if not name or name in prof:
            continue
        grade, label = _read_grade(text)
        if grade is None:
            continue
        vol, vkind = _read_vol(text)
        prof[name] = {"grade": grade, "label": label, "src": src,
                      "vol": vol, "vkind": vkind}
    labs = _fund_labels(list(prof.keys()))
    for n, r in prof.items():
        r["short"] = labs.get(n, n)
