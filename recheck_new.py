# -*- coding: utf-8 -*-
# recheck_new.py — v9.94 + 겹침 수리 이후, 사냥에서 걸렸던 질문들을 재질문해
#   고쳐졌는지 확인한다. (19문항, ~300원)
import re, time, requests

BASE = "http://localhost:8000/answer"

# (질문, 답에 있어야 하는 것, 있으면 안 되는 것)
CASES = [
    ("구개인연금은 몇 살부터, 얼마나 가입해야 연금으로 받을 수 있나요?", ["10년"], []),
    ("연금저축계좌에 있는 펀드를 담보로 대출받으면 평가금액의 몇 퍼센트까지 가능한가요?", ["60"], ["확인할 수 없습니다"]),
    ("연금계좌 증권담보융자의 대출 기간은 얼마나 되나요?", ["365"], []),
    ("M-STOCK으로 산 장외채권을 앱에서 팔 수도 있나요?", ["매도"], []),
    ("퇴직연금에서 회사채에 투자할 때 한도가 있나요?", ["40"], []),
    ("상장인프라펀드 매매등록 진행중인데 전송 버튼이 활성화되지 않습니다.", ["안내사항"], []),
    ("유상청약 시 예약청약 및 입금청약, 초과청약이 가능한가요?", ["초과청약"], []),
    ("신주인수권증서 매수 및 공매도 가능한가요?", ["매도만"], ["확인할 수 없습니다"]),
    ("적립식 주문단가와 주문수량은 어떻게 설정되나요?", ["주문"], ["범위를 벗어나"]),
    ("IRP 계좌를 다른 증권사로 옮길 때 보유 상품 그대로 이전되나요?", [], []),
    ("퇴직연금 계좌로 유상청약할 때 초과청약도 가능한가요?", ["불가"], []),
    ("은행용 공동인증서가 있는데, 공동인증서를 추가로 발급해야 하나요?", [], ["범위를 벗어나"]),
    ("과학기술발전장려금의 지급대상과 지급기준은 무엇인가요?", ["장려금"], ["범위를 벗어나"]),
    ("디폴트옵션 상품은 한번 지정하면 변경이나 취소가 불가능한가요?", ["변경"], ["확인할 수 없습니다"]),
    ("유선으로도 디폴트옵션 지정이 가능한가요?", ["가능"], ["확인할 수 없습니다"]),
    ("디폴트옵션(매도) → 디폴트옵션(매수) 교체매매가 가능한가요?", ["매도한 후"], ["확인할 수 없습니다"]),
    ("MP 구독 서비스 신청 대상은 누구인가요?", [], ["범위를 벗어나"]),
    ("MP 구독 서비스 신청/취소는 어디에서 하나요?", [], ["범위를 벗어나"]),
    ("2013년 3월 1일 전에 가입한 연금저축은 연금수령연차를 몇 년차부터 계산하나요?", ["6"], ["연연금금"]),
]

ok = bad = 0
for i, (q, must, never) in enumerate(CASES, 1):
    try:
        d = requests.get(BASE, params={"question_id": f"RC{i:02d}", "question": q},
                         timeout=120).json()
        ans = d.get("answer", "")
    except Exception as e:
        print(f"[{i:2d}] 서버 오류: {e}")
        bad += 1
        continue
    miss = [m for m in must if m not in ans]
    hit = [n for n in never if n in ans]
    good = not miss and not hit
    ok += good
    bad += not good
    tag = "고쳐짐" if good else f"잔존({'누락:' + ','.join(miss) if miss else ''}"\
                              f"{' 금지어:' + ','.join(hit) if hit else ''})"
    print(f"[{i:2d}] {tag} | {q}")
    if not good:
        print("     답변: " + re.sub(r"\s+", " ", ans)[:250])
    time.sleep(1.0)

print(f"\n결과: 고쳐짐 {ok} / 잔존 {bad} (총 {len(CASES)})")
