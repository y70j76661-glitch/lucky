# 오류 사냥: 약점을 겨냥한 10개 질문을 한 번에 실행
# 사용법: 서버(uvicorn)를 켜둔 상태에서 → python3 test_hunt.py
import requests

BASE = "http://localhost:8000/answer"

# (번호, 질문, 무엇을 확인하는가)
HUNTS = [
    (1, "연금저축 세액공제 한도가 400만원 맞지?",
     "틀린 전제 교정: 600만원이라고 바로잡아야 정답"),
    (2, "연금저축은 5년만 부어도 연금으로 받을 수 있어?",
     "가입기간 요건: 문서 근거로 답하는지 (문서엔 구상품 10년 규정 존재)"),
    (3, "직장인인데 어떤 연금 상품이 좋아?",
     "성향 날조 재현: trace가 '되묻기 모드'여야 정답"),
    (4, "연봉 6천만원에 연금저축 400만원, IRP에 300만원 넣으면 세액공제 얼마야?",
     "복합 계산: 합산 700만원 × 13.2% = 92.4만원이 맞는지"),
    (5, "IRP에 연 2000만원 넣으면 세액공제 얼마나 받아?",
     "한도 초과: 900만원까지만 인정한다고 답해야 정답"),
    (6, "연금 받을 때 세금 하나도 안 내는 거 맞지?",
     "오개념 교정: 연금소득세 3.3~5.5% 언급해야 정답"),
    (7, "국민연금 보험료율이 몇 퍼센트야?",
     "문서 밖 질문: '자료에서 확인할 수 없습니다'가 정답 (지어내면 오류)"),
    (8, "전업주부도 IRP 가입할 수 있어?",
     "가입 자격: 문서 근거로 소득 요건을 정확히 답하는지"),
    (9, "TDF랑 원리금보장형 중에 수수료 싼 게 뭐야?",
     "비교 테이블 모드: trace에 '비교 질문 감지' + 표 출력, 없는 정보는 '자료 없음'"),
    (10, "연금저축 중간에 깨면 얼마나 손해야?",
     "중도해지 불이익: 기타소득세 16.5% 수치가 정확한지"),
]


def main():
    print(f"오류 사냥 {len(HUNTS)}문항 시작 (질문마다 수십 초 걸릴 수 있어요)\n")
    for num, q, check in HUNTS:
        print("=" * 70)
        print(f"[{num}] {q}")
        print(f"    확인 포인트: {check}")
        print("-" * 70)
        try:
            r = requests.get(BASE, params={"question_id": str(num), "question": q}, timeout=180)
            d = r.json()
            print("[trace]", d.get("think_trace", ""))
            print()
            print("[answer]")
            print(d.get("answer", ""))
        except Exception as e:
            print(f"오류 발생: {e}")
        print()
    print("=" * 70)
    print("끝! 이상한 답변의 번호를 골라서 공유해 주세요.")


if __name__ == "__main__":
    main()
