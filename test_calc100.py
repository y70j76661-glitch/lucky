def _norm(s):
    # 콤마·공백·마크다운 강조(*)를 제거해 '**40**%' → '40%' 매칭
    return s.replace(",", "").replace(" ", "").replace("*", "")


def has(ans, v):
    return _norm(v) in _norm(ans)


def judge(ans, need, bad):
    for grp in need:
        if not any(has(ans, v) for v in grp):
            return False, [g[0] for g in need if not any(has(ans, v) for v in g)]
    if any(has(ans, b) for b in bad):
        return False, ["금지값출현:" + ",".join(bad)]
    return True, []


