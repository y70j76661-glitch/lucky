def main():
    print(f"종합 Open 완결성 {len(Q)}문항 — {BASE}\n")
    ft = open("open_out.txt", "w", encoding="utf-8")
    weak = []
    for qid, q, facets in Q:
        t0 = time.time()
        try:
            a = requests.get(BASE, params={"question_id": qid, "question": q}, timeout=180).json().get("answer", "") or ""
        except Exception as e:
            a = f"(요청실패:{str(e)[:40]})"
        dt = time.time() - t0
        flat = re.sub(r"\s+", "", a)
        cov = {}
        for fname, kws in facets.items():
            cov[fname] = any(re.sub(r"\s+", "", k) in flat for k in kws)
        missing = [f for f, ok in cov.items() if not ok]
        n = sum(cov.values())
        tag = "완결" if not missing else f"누락:{missing}"
        print(f"  [{qid}] {dt:4.1f}s  {n}/5  {tag}")
        if missing: weak.append((qid, missing))
        ft.write(f"\n{'='*70}\n[{qid}] {q}\n요소커버 {n}/5  누락={missing}\n--- 답변 ---\n{a}\n")
        time.sleep(0.3)
    ft.close()
    print("\n" + "=" * 60)
    if weak:
        print(f"요소 누락 {len(weak)}문항:")
        for qid, m in weak:
            print(f"  [{qid}] {m}")
        print("→ open_out.txt 원문 보고 '진짜 누락'인지 '키워드 표기차'인지 판단. 치명적 누락만 수정.")
    else:
        print("5문항 모두 5요소 완결 → 종합 Open 완결성 통과")
    print("=" * 60)


if __name__ == "__main__":
    main()
